"""Build the two artifacts.

    ClaudeEnvGuard.exe       windowed: serves the page, opens the browser, and
                             keeps a Claude-styled control window alive
    ClaudeEnvGuard-cli.exe   console: --json / --text / --md / --web for scripts

Both carry the same package and the same HTML, so there is exactly one
implementation of every check.

The icon comes from `assets/claude-env-guard.ico`, regenerated by
`tools/make_icon.py`, which draws the same twelve-spoke mark the page draws in
SVG — the taskbar icon and the page header cannot drift apart.

On onefile: the bootloader extracts itself to a temp directory before running,
which fails inside a cloud-sync folder whose files are reparse-point placeholders
(Nutstore keeps them that way). That is why the README says to keep the exe out of
such a folder; it is a limitation of the packaging mode, reproduced with a
three-line hello-world build.
"""

import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(ROOT, "dist")
BUILD = os.path.join(ROOT, "build")
ICON = os.path.join(ROOT, "assets", "claude-env-guard.ico")
HTML = os.path.join(ROOT, "ClaudeEnvGuard.html")

COMMON = [
    "--noconfirm",
    "--clean",
    "--onefile",
    "--distpath", DIST,
    "--workpath", BUILD,
    "--specpath", BUILD,
    "--add-data", f"{HTML};.",
    "--add-data", f"{os.path.join(ROOT, 'assets')};assets",
    # Only libraries this tool never imports. `email` is deliberately NOT here:
    # urllib.request imports it, so excluding it builds an exe that dies with
    # ModuleNotFoundError on the first network call — found by running the
    # artifact, not by reading the build log.
    "--exclude-module", "numpy",
    "--exclude-module", "pandas",
    "--exclude-module", "matplotlib",
    "--exclude-module", "PIL",
    "--exclude-module", "pytest",
]


def build(name: str, windowed: bool) -> str:
    args = [
        sys.executable, "-m", "PyInstaller",
        *COMMON,
        "--name", name,
        "--windowed" if windowed else "--console",
    ]
    if os.path.isfile(ICON):
        args += ["--icon", ICON]
    args.append(os.path.join(ROOT, "run.py"))
    print("->", " ".join(args))
    subprocess.run(args, check=True, cwd=ROOT)
    return os.path.join(DIST, name + ".exe")


def main() -> int:
    # The console is GBK on a zh-CN machine; a non-ASCII progress mark would
    # raise UnicodeEncodeError at the very end of an otherwise successful build.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    for directory in (DIST, BUILD):
        if os.path.isdir(directory):
            shutil.rmtree(directory, ignore_errors=True)

    for name, windowed in (("ClaudeEnvGuard", True), ("ClaudeEnvGuard-cli", False)):
        path = build(name, windowed)
        size = os.path.getsize(path) / (1024 * 1024)
        print(f"OK {os.path.relpath(path, ROOT)}  {size:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
